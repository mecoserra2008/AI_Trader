"""Gate G1 (phase 4) reproduce command, from the repo root:

    uv run --extra vecopen python vecopen/tests/leak/run_g1.py

Runs the leak audit (``leakkit.run_asset``: SPEC section 6 leak tests 1 to 3 plus the construction-rule checks) on
every crypto asset of ``config/baseline.yaml``, one asset at a time; reports that no CFD research data exists yet; runs
the cross-asset matching-timing check (covariates and timestamps only); runs the fast ``tests/leak`` pytest suite;
writes ``reports/phase_4_g1_results.json`` and ``reports/phase_4_g1_tables.md``; and appends one registry line
(phase 4, kind ``audit``) with pass/fail per test per asset.

Blindness (G2 comes later): nothing here reads a label table, and no placebo touch count is computed, stored or
printed (successful checks are counted on treated outputs only). Reads ``data/research`` only, never
``data/holdout``. Resources: one asset at a time; the parent and its worker run alternately (never concurrently), with
POLARS_MAX_THREADS=2.

Options: ``--assets A,B`` (subset), ``--n 200`` (timestamps per asset), ``--resume`` (keep assets already in the results
file when the harness hash matches), ``--no-registry``, ``--skip-tests``, ``--results``/``--tables`` (other paths).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET
from pathlib import Path

os.environ.setdefault("POLARS_MAX_THREADS", "2")
os.environ.setdefault("OMP_NUM_THREADS", "2")
HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import leakkit as lk  # noqa: E402
from vecopen import registry  # noqa: E402
from vecopen.config import PROJECT_ROOT, load_config  # noqa: E402
from vecopen.data import research_path  # noqa: E402

RESULTS = PROJECT_ROOT / "reports" / "phase_4_g1_results.json"
TABLES = PROJECT_ROOT / "reports" / "phase_4_g1_tables.md"


def harness_sha256() -> str:
    h = hashlib.sha256()
    for f in sorted(HERE.glob("*.py")):
        h.update(f.name.encode() + b"\0" + f.read_bytes().replace(b"\r\n", b"\n"))
    return h.hexdigest()


def run_pytest() -> dict[str, int]:
    with tempfile.TemporaryDirectory() as td:
        xml = Path(td) / "junit.xml"
        proc = subprocess.run([sys.executable, "-m", "pytest", str(HERE), "-q", "-p", "no:cacheprovider",
                               f"--junitxml={xml}"], cwd=PROJECT_ROOT.parent, check=False)
        if not xml.exists():
            return {"tests": 0, "passed": 0, "failed": 0, "errors": 1, "skipped": 0, "exit_code": proc.returncode}
        root = ET.parse(xml).getroot()
        suites = [root] if root.tag == "testsuite" else list(root.iter("testsuite"))
        tot = {k: sum(int(s.get(k, 0)) for s in suites) for k in ("tests", "failures", "errors", "skipped")}
    return {"tests": tot["tests"], "passed": tot["tests"] - tot["failures"] - tot["errors"] - tot["skipped"],
            "failed": tot["failures"], "errors": tot["errors"], "skipped": tot["skipped"], "exit_code": proc.returncode}


def _write_json(p: Path, obj: object) -> None:
    tmp = p.with_name(p.name + ".tmp")
    tmp.write_text(json.dumps(obj, indent=1, sort_keys=True, default=str), encoding="utf-8", newline="\n")
    os.replace(tmp, p)


def verdict(r: dict) -> dict[str, bool]:
    return {"test1_truncation": bool(r["test1"]["pass"] and r["test1"]["literal_pass"] is not False
                                     and r["state_timestamps_le_t"]),
            "test2_perturbation": bool(r["test2"]["pass"]),
            "test3_timestamp_audit": bool(r["test3"]["pass"]),
            "construction_rules": bool(r["rules_pass"] and r["late_origin_flags"] == 0
                                       and not r["labels_module_loaded_during_run"]
                                       and all(v.get("misaligned", 0) == 0 and v.get("partial_only_first_bar", True)
                                               for k, v in r["session_anchors"].items() if isinstance(v, dict)))}


def tables(res: dict) -> str:
    A = res["assets"]
    L = ["# Phase 4 (gate G1) leak audit tables", "",
         "Generated by `uv run --extra vecopen python vecopen/tests/leak/run_g1.py`. Do not edit by hand. "
         "No label is read and no placebo touch count is shown (successful checks are counted on treated outputs).", "",
         f"Config sha256 `{res['config_sha256']}`; harness sha256 `{res['harness_sha256']}`.", "",
         "## 1. Verdict per asset", "",
         "| asset | test 1 truncation (passed / t; literal run) | test 2 perturbation (passed / t) | test 3 timestamp "
         "audit | construction rules | stored covariates = stream | treated events audited | stream bars | "
         "runtime (s) | peak RSS parent / worker (MB) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for a, r in A.items():
        v = r["verdict"]
        t1, t2 = r["test1"], r["test2"]
        sc = r["stored"]
        st = "n/a" if not sc.get("present") else ("yes" if sc.get("treated_identical") and sc.get("p1_nonorigin_identical")
                                                 else "NO")
        L.append(f"| {a} | {'PASS' if v['test1_truncation'] else 'FAIL'} ({t1['passed']}/{t1['n']}; literal "
                 f"{'pass' if t1['literal_pass'] else 'FAIL'}) | {'PASS' if v['test2_perturbation'] else 'FAIL'} "
                 f"({t2['passed']}/{t2['n']}) | {'PASS' if v['test3_timestamp_audit'] else 'FAIL'} | "
                 f"{'PASS' if v['construction_rules'] else 'FAIL'} | {st} | {r['audit']['treated_events']:,} | "
                 f"{r['stream_bars']:,} | {r['seconds']['total']} | {r['peak_rss_mb']['parent']} / "
                 f"{r['peak_rss_mb']['worker']} |")
    L += ["", f"CFD assets: {res['cfd']['note']}", ""]
    # 2. coverage of tests 1 and 2
    L += ["## 2. Coverage of tests 1 and 2", "",
          "| asset | timestamps | from-scratch (literal) runs | warm-start window days min / median / max | "
          "bars replayed (test 1) | bars replayed <= t / after t (test 2) | worker s (1 / 2) |",
          "|---|---|---|---|---|---|---|"]
    for a, r in A.items():
        t1, t2 = r["test1"], r["test2"]
        w = t1["window_days_min_median_max"]
        L.append(f"| {a} | {t1['n']} | {t1['literal_runs']} | {' / '.join(str(x) for x in w) if w else ''} | "
                 f"{t1['bars_replayed']:,} | {t2['bars_replayed']:,} / {t2['bars_after_t_replayed']:,} | "
                 f"{t1['worker_seconds']} / {t2['worker_seconds']} |")
    # 3. checks
    names = sorted({c for r in A.values() for c in r["audit"]["checks"]})
    L += ["", "## 3. Checks summed over assets", "",
          "`ok` counts successes on treated outputs (and bar-level checks); placebo outputs are checked too, but only "
          "their failures are counted.", "",
          "| check | ok | fail | placebo outputs checked |", "|---|---|---|---|"]
    for c in names:
        ok = sum(r["audit"]["checks"].get(c, {}).get("ok", 0) for r in A.values())
        fl = sum(r["audit"]["checks"].get(c, {}).get("fail", 0) for r in A.values())
        pc = any(r["audit"]["checks"].get(c, {}).get("placebo_checked") for r in A.values())
        L.append(f"| `{c}` | {ok:,} | {fl:,} | {'yes' if pc else 'no'} |")
    nv = {}
    for r in A.values():
        for k, v in r["audit"]["nonvacuity"].items():
            nv[k] = nv.get(k, 0) + v
    L += ["", "Non-vacuity of the shift checks (treated): " + ", ".join(f"{k} {v:,}" for k, v in sorted(nv.items())),
          "", "Regime running mean TR vs exact fsum, max relative error over assets: "
          f"{max(r['audit']['regime_running_sum_max_rel_err'] for r in A.values()):.2e}"]
    # 4. provenance
    L += ["", "## 4. Provenance of resampled bars (test 3, rule 1)", "",
          "| tf | bars (all assets) | bars with a source after their close | bars with a source before their open | "
          "keys equal the real frame | source count = n_base |", "|---|---|---|---|---|---|"]
    tfs = list(next(iter(A.values()))["provenance"])
    for tf in tfs:
        ps = [r["provenance"][tf] for r in A.values()]
        L.append(f"| {tf} | {sum(p['bars'] for p in ps):,} | {sum(p['max_src_after_close'] for p in ps)} | "
                 f"{sum(p['min_src_before_open'] for p in ps)} | {all(p['keys_match_real_frame'] for p in ps)} | "
                 f"{all(p['count_matches_n_base'] for p in ps)} |")
    # 5. sessions
    L += ["", "## 5. Session anchors (rule 4)", "",
          "| tf | bars | misaligned to the configured session | assets whose only partial bucket is the first bar | "
          "assets with a partial first bucket |", "|---|---|---|---|---|"]
    for tf in tfs:
        ss = [r["session_anchors"][tf] for r in A.values()]
        L.append(f"| {tf} | {sum(s['bars'] for s in ss):,} | {sum(s['misaligned'] for s in ss)} | "
                 f"{sum(s['partial_only_first_bar'] for s in ss)} / {len(ss)} | {sum(s['partial_buckets'] > 0 for s in ss)} |")
    L += ["", "Sessions: " + ", ".join(sorted({r['session_anchors']['session'] for r in A.values()})) +
          f"; sessions.yaml sha256 `{res['sessions_sha256']}` (phase 1 registered "
          f"`{res['sessions_sha256_phase1']}`: {'equal' if res['sessions_sha256'] == res['sessions_sha256_phase1'] else 'DIFFERENT'})."]
    # 6. matching timing
    m = res.get("matching_timing")
    if m:
        L += ["", "## 6. Family-1 matching: timing of the matched placebo (covariates and timestamps only)", "",
              "| group | pairs | placebo t0 after treated t0 | same calendar year (t0 of both) | cross-asset pairs |",
              "|---|---|---|---|---|"]
        for g, v in m["groups"].items():
            L.append(f"| {g} | {v['pairs']:,} | {v['placebo_later_frac']:.3f} | {v['same_year_frac']:.3f} | "
                     f"{v['cross_asset_frac']:.3f} |")
    # 7. stored tables
    L += ["", "## 7. Stored phase 3 tables vs the audited stream", "",
          "| asset | treated covariates identical | family-1 covariates identical | label columns in events.parquet | "
          "outcome columns in levels.parquet | late_origin flags |", "|---|---|---|---|---|---|"]
    for a, r in A.items():
        sc = r["stored"]
        if not sc.get("present"):
            L.append(f"| {a} | n/a | n/a | n/a | n/a | {r['late_origin_flags']} |")
            continue
        L.append(f"| {a} | {sc['treated_identical']} | {sc['p1_nonorigin_identical']} | "
                 f"{sc['label_columns_in_events_table'] or 'none'} | {', '.join(sc.get('levels_outcome_columns', []))} | "
                 f"{r['late_origin_flags']} |")
    t = res.get("pytest")
    if t:
        L += ["", f"## 8. tests/leak pytest suite: {t['passed']} passed, {t['failed']} failed, {t['errors']} errors, "
              f"{t['skipped']} skipped (exit code {t['exit_code']})."]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--assets", default="")
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--resume", action="store_true")
    ap.add_argument("--no-registry", action="store_true")
    ap.add_argument("--skip-tests", action="store_true")
    ap.add_argument("--results", default=str(RESULTS))
    ap.add_argument("--tables", default=str(TABLES))
    args = ap.parse_args(argv)

    cfg = load_config()
    from vecopen.bars import load_sessions

    sessions = load_sessions()
    hsh = harness_sha256()
    assets = args.assets.split(",") if args.assets else list(cfg.data["assets"]["crypto"]["symbols"])
    cfd = list(cfg.data["assets"]["cfd"]["candidates"])
    cfd_present = [a for a in cfd if research_path(a).exists()]
    out_p, tab_p = Path(args.results), Path(args.tables)
    res: dict = {"config_sha256": cfg.sha256, "harness_sha256": hsh, "n_per_asset": args.n, "assets": {},
                 "sessions_sha256": sessions.sha256,
                 "sessions_sha256_phase1": "9add7ce4e40a89ffce64e1f8a8f4cdcc47e82efdcad178cc798de1e80e2a2607",
                 "cfd": {"candidates": cfd, "with_research_data": cfd_present,
                         "note": ("none of the 16 CFD candidates has research data yet (no cTrader keys; phase 1), "
                                  "so G1 covers the 20 crypto assets only and must be re-run when CFD data lands")
                         if not cfd_present else f"CFD research data present for {cfd_present}: NOT audited here"}}
    if args.resume and out_p.exists():
        old = json.loads(out_p.read_text(encoding="utf-8"))
        if old.get("harness_sha256") == hsh and old.get("config_sha256") == cfg.sha256 and old.get("n_per_asset") == args.n:
            res["assets"] = {a: r for a, r in old.get("assets", {}).items() if a in assets}
    T = time.perf_counter()
    for a in assets:
        if a in res["assets"]:
            print(f"{a}: kept from {out_p.name}", flush=True)
            continue
        r = lk.run_asset(a, args.n, log=lambda m: print(m, flush=True))
        r["stored"] = lk.stored_covariates_check(a, r.pop("_cov_rows"))
        r["verdict"] = verdict(r)
        res["assets"][a] = r
        _write_json(out_p, res)
        v = r["verdict"]
        print(f"{a}: " + " ".join(f"{k}={'PASS' if x else 'FAIL'}" for k, x in v.items())
              + f" | t1 {r['test1']['passed']}/{r['test1']['n']} t2 {r['test2']['passed']}/{r['test2']['n']}"
              + f" | {r['seconds']['total']} s | peak {r['peak_rss_mb']}", flush=True)
    res["matching_timing"] = lk.matching_timing_check(list(res["assets"]))
    res["runtime_seconds"] = round(time.perf_counter() - T, 1)
    if not args.skip_tests:
        res["pytest"] = run_pytest()
    _write_json(out_p, res)
    md = tables(res)
    tab_p.write_text(md, encoding="utf-8", newline="\n")
    per_asset = {a: r["verdict"] for a, r in res["assets"].items()}
    all_pass = all(all(v.values()) for v in per_asset.values()) and len(per_asset) == len(
        cfg.data["assets"]["crypto"]["symbols"]) and (args.skip_tests or res["pytest"]["failed"] == 0 and
                                                       res["pytest"]["errors"] == 0)
    print(md)
    print(f"G1 {'PASS' if all_pass else 'FAIL'} on {len(per_asset)} assets")
    if not args.no_registry:
        metrics = {"gate": "G1", "verdict": "pass" if all_pass else "fail", "per_asset": per_asset,
                   "n_timestamps_per_asset": args.n, "cfd": res["cfd"]["note"],
                   "harness_sha256": hsh,
                   "results_sha256": hashlib.sha256(out_p.read_bytes()).hexdigest(),
                   "tables_sha256": hashlib.sha256(md.encode("utf-8")).hexdigest(),
                   "pytest": res.get("pytest"), "runtime_seconds": res["runtime_seconds"]}
        rec = registry.append(4, metrics, kind="audit", config=cfg,
                              note="phase 4 gate G1 leak audit: SPEC section 6 leak tests 1-3 on every crypto asset "
                                   "(tests/leak, auditor-owned); CFDs have no data yet")
        print(f"registry line {rec['seq'] + 1} appended (kind audit): line_sha256 {rec['line_sha256']}")
    return 0 if all_pass else 1


if __name__ == "__main__":
    sys.exit(main())
